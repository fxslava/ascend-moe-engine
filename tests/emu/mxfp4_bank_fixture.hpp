// A synthetic bank of per-expert MXFP4 weight matrices, generated in memory
// from a seed the caller prints (CLAUDE.md section 4.5 -- no disk fixtures).
//
// SHARED, NOT COPIED. Two suites audit the W4A16 family -- the monolithic
// oracle in test_dsv4_moe_prefill_cube_emu.cpp and the flash-tiled one in
// test_dsv4_moe_prefill_flash_emu.cpp -- and their numbers are only
// comparable if they are generated by the SAME code from the same seed. It
// also keeps the nibble-order convention (kMxfp4LowNibbleFirst) written out
// exactly once on the test side, which is the point: a second transcription of
// a packing convention is a second thing that can be wrong.
//
// Header-only and standard-library-only, like emu_test_support.hpp: the emu
// suite must build with a stock host g++ and no toolkit present.

#ifndef TESTS_EMU_MXFP4_BANK_FIXTURE_HPP
#define TESTS_EMU_MXFP4_BANK_FIXTURE_HPP

#include "moe/emu/dsv4_layers.h"
#include "moe/emu/fp8_types.hpp"

#include <cmath>
#include <cstddef>
#include <cstdint>
#include <limits>
#include <random>
#include <vector>

namespace mxfp4_fixture {

using moe::emu::DecodeFp4E2M1;
using moe::emu::DecodeFp8E8M0;
using moe::emu::kMxfp4GroupSize;
using moe::emu::kMxfp4LowNibbleFirst;
using moe::emu::Mxfp4Matrix;

// Nearest E2M1 code by exhaustive search over the 16 codes. Exhaustive rather
// than arithmetic because the set is tiny and a closed-form encoder is one
// more thing to get wrong in a fixture.
inline std::uint8_t EncodeFp4Nearest(float value) {
  std::uint8_t best = 0;
  float error = std::numeric_limits<float>::infinity();
  for (std::uint8_t code = 0; code < 16; ++code) {
    const float candidate = std::fabs(value - DecodeFp4E2M1(code));
    if (candidate < error) {
      best = code;
      error = candidate;
    }
  }
  return best;
}

struct Bank {
  int rows = 0;
  int cols = 0;
  std::vector<std::uint8_t> packed;  // [experts, rows, cols/2]
  std::vector<std::uint8_t> scales;  // [experts, rows, cols/32]

  std::size_t PackedStride() const {
    return static_cast<std::size_t>(rows) * static_cast<std::size_t>(cols / 2);
  }
  std::size_t ScaleStride() const {
    return static_cast<std::size_t>(rows) *
           static_cast<std::size_t>(cols / kMxfp4GroupSize);
  }
  Mxfp4Matrix View(int expert) const {
    return {packed.data() + static_cast<std::size_t>(expert) * PackedStride(),
            scales.data() + static_cast<std::size_t>(expert) * ScaleStride(),
            rows, cols};
  }
};

// Scale codes stay in 125..128, which is where a real checkpoint's
// micro-scales sit and well inside the exact MXFP4 -> BF16 domain that
// test_dsv4_moe_prefill_cube_emu.cpp establishes. The expert id participates
// in the pattern so that reading the wrong expert cannot go unnoticed.
inline Bank MakeBank(int rows, int cols, int experts, std::mt19937_64& rng) {
  Bank bank;
  bank.rows = rows;
  bank.cols = cols;
  bank.packed.resize(static_cast<std::size_t>(experts) * rows * (cols / 2));
  bank.scales.resize(static_cast<std::size_t>(experts) * rows *
                     (cols / kMxfp4GroupSize));
  std::normal_distribution<float> draw(0.0F, 1.3F);
  const int groups = cols / kMxfp4GroupSize;
  for (int e = 0; e < experts; ++e) {
    for (int row = 0; row < rows; ++row) {
      for (int group = 0; group < groups; ++group) {
        const std::uint8_t scale_code =
            static_cast<std::uint8_t>(125u + ((row + group + e) % 4u));
        bank.scales[static_cast<std::size_t>(e) * bank.ScaleStride() +
                    static_cast<std::size_t>(row) * groups + group] =
            scale_code;
        const float scale = DecodeFp8E8M0(scale_code);
        for (int col = group * kMxfp4GroupSize;
             col < (group + 1) * kMxfp4GroupSize; col += 2) {
          const std::uint8_t a = EncodeFp4Nearest(draw(rng) / scale);
          const std::uint8_t b = EncodeFp4Nearest(draw(rng) / scale);
          const std::uint8_t low = kMxfp4LowNibbleFirst ? a : b;
          const std::uint8_t high = kMxfp4LowNibbleFirst ? b : a;
          bank.packed[static_cast<std::size_t>(e) * bank.PackedStride() +
                      static_cast<std::size_t>(row) * (cols / 2) + col / 2] =
              static_cast<std::uint8_t>(low | (high << 4u));
        }
      }
    }
  }
  return bank;
}

// One logical element of a dequantized MXFP4 matrix, built from the PUBLIC row
// helper. Used by audits that must not reuse the GEMV or the per-element
// decode they are auditing.
inline float DequantElement(const Mxfp4Matrix& w, int row, int col,
                            std::vector<float>* row_scratch) {
  row_scratch->resize(static_cast<std::size_t>(w.cols));
  moe::emu::mxfp4_dequant_row_bf16_cpu(w, row, row_scratch->data());
  return (*row_scratch)[static_cast<std::size_t>(col)];
}

// silu(z) = z * sigmoid(z), with the same -80 guard the oracles use. An
// independent transcription for the tests, not a call into the library.
inline float SiluRef(float z) {
  if (z < -80.0F) return 0.0F;
  return z / (1.0F + std::exp(-z));
}

}  // namespace mxfp4_fixture

#endif  // TESTS_EMU_MXFP4_BANK_FIXTURE_HPP
