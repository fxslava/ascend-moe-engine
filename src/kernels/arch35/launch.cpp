// -----------------------------------------------------------------------------
// launch.cpp -- host-side launch layer for the five arch35 direct kernels.
//
// See include/moe/kernels/arch35/launch.hpp for the ownership contract. In
// short: the caller owns every operand GM buffer; this file owns geometry
// validation, the TilingData staging buffer, and the dispatch.
//
// LAUNCH MECHANISM
// This translation unit is compiled by BiSheng as an ASC (device-language) TU
// and dispatches with the triple-chevron direct-launch syntax:
//
//     kernel<<<blockDim, l2ctrl, stream>>>(args...)
//
// which BiSheng lowers to aclrtLaunchKernelWithHostArgs /
// aclrtBinaryLoadFromData / aclrtGetFuncBySymbol against libascendcl.
//
// It deliberately does NOT use ACLRT_LAUNCH_KERNEL / `aclrtlaunch_<kernel>`.
// That form needs host stubs generated by the op-package (legacy) flow; in
// CANN 9.2.0-beta.2 the ASC-language flow passes -DGEN_ACLRT=<dir> but nothing
// in the toolchain consumes it (the define appears only in FindASC.cmake, and
// `ACLRT_LAUNCH_KERNEL` only inside extract_host_stub.py), so no stub is
// emitted and such a build fails at link with five undefined symbols. The
// chevron form is what this toolkit actually supports.
//
// Consequence for the build: this file must be compiled with BiSheng, not the
// host compiler. The public header stays plain C++ over <acl/acl.h>, so host
// TUs compiled with g++ can call these wrappers and link against the BiSheng
// objects (verified: a g++ main links cleanly with these objects).
//
// Chevron calls return void, so a dispatch error surfaces at the following
// stream synchronization rather than from the call itself.
//
// NOT YET EXECUTED: no Ascend NPU exists on the development workstation, so
// this file is verified to compile and link only.
// -----------------------------------------------------------------------------

