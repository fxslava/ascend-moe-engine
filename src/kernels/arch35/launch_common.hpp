#ifndef MOE_KERNELS_ARCH35_LAUNCH_COMMON_HPP
#define MOE_KERNELS_ARCH35_LAUNCH_COMMON_HPP
// -----------------------------------------------------------------------------
// launch_common.hpp -- what the five src/ops/<op>/op_host/<op>.cpp launchers
// share: tiling staging, the GM pointer narrowing, the post-launch sync, and
// the failure record that makes `Status::launch_error` diagnosable.
//
// LAUNCH MECHANISM
// Each op_host TU is compiled by BiSheng as an ASC (device-language) TU and
// dispatches with the triple-chevron direct-launch syntax:
//
//     kernel<<<blockDim, l2ctrl, stream>>>(args...)
//
// which BiSheng lowers to aclrtLaunchKernelWithHostArgs /
// aclrtBinaryLoadFromData / aclrtGetFuncBySymbol against libascendcl.
//
// It deliberately does NOT use ACLRT_LAUNCH_KERNEL / `aclrtlaunch_<kernel>`.
// That form needs host stubs generated by the op-package (legacy) flow; in
// CANN 9.2.0-beta.2 the ASC-language flow passes -DGEN_ACLRT=<dir> but nothing
// in the toolchain consumes it (the define appears only in FindASC.cmake, and
// `ACLRT_LAUNCH_KERNEL` only inside extract_host_stub.py), so no stub is
// emitted and such a build fails at link with five undefined symbols. The
// chevron form is what this toolkit actually supports.
//
// Chevron calls return void, so a dispatch error surfaces at the following
// stream synchronization rather than from the call itself. That is exactly why
// RecordAclFailure() exists: without it every distinct failure -- a tiling
// malloc, a tiling H2D copy, a bad grid, a device-side fault -- collapses into
// one undifferentiated `launch_error` with nothing to act on.
// -----------------------------------------------------------------------------

#include "moe/kernels/arch35/launch.hpp"

#include <cstddef>
#include <cstdint>

namespace moe::kernels::arch35 {
namespace detail {

inline std::size_t AlignUp(std::size_t value, std::size_t align) noexcept {
  return (value + align - 1) / align * align;
}

// Alignment of the tiling staging allocation. 32 B is the GM alignment the
// contract fixes for every operand.
inline constexpr std::size_t kTilingAlignBytes = 32;

// Records which ACL call failed, for LastLaunchFailure(). `op` and `call` must
// be string literals (they are stored by pointer, not copied).
void RecordAclFailure(const char* op, const char* call, int acl_error) noexcept;
void ClearLaunchFailure() noexcept;

// ---------------------------------------------------------------------------
// AIV core count -- queried, never hardcoded
// ---------------------------------------------------------------------------
// THERE IS NO CORRECT LITERAL FOR THIS. Ascend 950PR ships as several parts,
// and the toolkit's own platform configs
// (x86_64-linux/data/platform_config/Ascend950PR_*.ini) enumerate them --
// always 1 Cube : 2 Vector:
//
//     950z (dev)                     4 cube /  8 vector
//     9579 / 957b / 957c / 957d     28 cube / 56 vector
//     9589 / 958b                   32 cube / 64 vector
//     9599                          36 cube / 72 vector
//
// So every hardcoded pure-AIV grid in this tree is wrong on some part, and a
// grid of 32 is the CUBE count of the 9589 SKU rather than its Vector count
// -- half occupancy on that part, 44% on a 9599.
//
// Returns 0 when the query fails or reports something unusable. Callers treat
// that as "use the conservative fallback", NOT as a launch failure: a
// suboptimal grid is a throughput bug, while refusing to launch because a
// capability query failed would turn it into a correctness-visible one. The
// failure is still recorded so LastLaunchFailure() can explain a surprising
// grid (§3.5).
std::uint32_t QueryAivCoreCount() noexcept;

// ---------------------------------------------------------------------------
// Tiling staging
//
// Allocates a device buffer, copies the POD in, and releases it in the
// destructor. Release() runs only after the stream has been synchronized, so
// the kernel cannot still be reading it.
// ---------------------------------------------------------------------------
class TilingStaging {
 public:
  TilingStaging() = default;
  TilingStaging(const TilingStaging&) = delete;
  TilingStaging& operator=(const TilingStaging&) = delete;

  ~TilingStaging() { Release(); }

  // Copies `bytes` from `host` into a fresh device allocation, reporting which
  // call failed through RecordAclFailure so the caller's `launch_error` can be
  // traced to the allocation or to the copy.
  Status Stage(const char* op, const void* host, std::size_t bytes) {
    const std::size_t padded = AlignUp(bytes, kTilingAlignBytes);
    aclError rc = aclrtMalloc(&device_, padded, ACL_MEM_MALLOC_HUGE_FIRST);
    if (rc != ACL_SUCCESS) {
      device_ = nullptr;
      RecordAclFailure(op, "aclrtMalloc(tiling)", static_cast<int>(rc));
      return Status::launch_error;
    }
    // The allocation is rounded up to 32 B but the POD is 32/40/48/64 B, so
    // for three of the five operators `padded > bytes`. Zero the whole
    // allocation first: otherwise those trailing bytes reach the device
    // uninitialized, and any future kernel that reads a reserved field past
    // sizeof(POD) would see nondeterministic data. Cheap -- 64 B, once per
    // launch, on a buffer that is about to be written anyway.
    rc = aclrtMemset(device_, padded, 0, padded);
    if (rc != ACL_SUCCESS) {
      RecordAclFailure(op, "aclrtMemset(tiling)", static_cast<int>(rc));
      Release();
      return Status::launch_error;
    }
    // Synchronous copy: the tiling must be resident before the launch is
    // enqueued, and it is a few dozen bytes, so there is nothing to overlap.
    rc = aclrtMemcpy(device_, padded, host, bytes, ACL_MEMCPY_HOST_TO_DEVICE);
    if (rc != ACL_SUCCESS) {
      RecordAclFailure(op, "aclrtMemcpy(tiling H2D)", static_cast<int>(rc));
      Release();
      return Status::launch_error;
    }
    return Status::success;
  }

  void* get() const noexcept { return device_; }

  void Release() noexcept {
    if (device_ != nullptr) {
      (void)aclrtFree(device_);
      device_ = nullptr;
    }
  }

 private:
  void* device_ = nullptr;
};

// Narrows a typed device pointer to the untyped byte pointer the kernel ABI
// takes, dropping const: the kernels treat their inputs as read-only, but the
// ABI is simply untyped. Returns uint8_t* rather than void* because a chevron
// argument must be convertible to GM_ADDR (__gm__ uint8_t*), and void* is not.
template <typename T>
inline std::uint8_t* Gm(const T* p) noexcept {
  return const_cast<std::uint8_t*>(reinterpret_cast<const std::uint8_t*>(p));
}

template <typename T>
inline std::uint8_t* Gm(T* p) noexcept {
  return reinterpret_cast<std::uint8_t*>(p);
}

inline std::uint8_t* Gm(void* p) noexcept { return static_cast<std::uint8_t*>(p); }

// Synchronize before the staging buffer goes out of scope. See launch.hpp for
// why the sync lives here in v1. A chevron launch returns void, so this is
// also where a dispatch failure or a device-side fault is first observable --
// and the only place their aclError can be captured.
inline Status FinishLaunch(const char* op, aclrtStream stream) {
  const aclError rc = aclrtSynchronizeStream(stream);
  if (rc != ACL_SUCCESS) {
    RecordAclFailure(op, "aclrtSynchronizeStream(after launch)",
                     static_cast<int>(rc));
    return Status::launch_error;
  }
  return Status::success;
}

}  // namespace detail
}  // namespace moe::kernels::arch35

#endif  // MOE_KERNELS_ARCH35_LAUNCH_COMMON_HPP
