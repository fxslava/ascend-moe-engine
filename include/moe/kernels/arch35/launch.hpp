// -----------------------------------------------------------------------------
// launch.hpp -- host-side launch layer for the five arch35 direct kernels,
// as specified in docs/kernel_contracts_spec.md.
//
// OWNERSHIP CONTRACT (follows the spec, which names every pointer `*_gm`):
// the caller owns and populates all device GM buffers and passes DEVICE
// pointers. These wrappers do NOT allocate or copy operand data. What they own
// is the part the kernel ABI needs but the signature has no parameter for:
//
//   * validating the geometry against the v1 contract before enqueue (the
//     kernels reject bad tiling by returning early, which on device is a
//     silent no-op -- so the host is where a wrong shape must be caught),
//   * building the versioned TilingData POD and staging it in device memory,
//   * dispatching with the contract's block_dim,
//   * tearing the tiling staging down.
//
// STREAM AND TILING LIFETIME
// The tiling buffer must stay live until the kernel has consumed it. Rather
// than hand that lifetime back to the caller (the spec gives the signature no
// tiling parameter), each wrapper synchronizes `stream` before releasing its
// staging buffer. That makes every call self-contained and correct, at the
// cost of a per-launch sync: a correctness-first v1, matching how the spec
// describes the UB budgets. A pipelined variant would need a caller-owned
// tiling allocation, and is deliberately not invented here.
//
// Because of that sync, these wrappers are suitable for the verification
// harness as-is. A throughput benchmark that wants to exclude host/device
// synchronization from its timed region needs the pipelined variant above.
//
// BUILD REQUIREMENT
// This header is plain C++ over <acl/acl.h>, so any host TU (g++ included) can
// call these wrappers. The IMPLEMENTATION, however, must be compiled by
// BiSheng: it dispatches with the triple-chevron direct-launch syntax, which
// is the form CANN 9.2.0-beta.2 actually supports (the `aclrtlaunch_<kernel>`
// stubs that ACLRT_LAUNCH_KERNEL needs are not generated by this toolkit's
// ASC flow -- see the note in launch.cpp). Linking g++ host objects against
// the BiSheng-compiled launch objects works; see cmake/arch35_device.cmake.
//
// NOT YET EXECUTED: there is no Ascend NPU on the development workstation
// (no /dev/davinci*, no driver, npu-smi absent), so this layer has been
// verified to COMPILE and LINK against CANN 9.2 / libascendcl only. No call
// here has ever run on hardware. Treat first-run behaviour as unproven.
// -----------------------------------------------------------------------------

